SELECT l1.`level1`, MIN(pc.`id`) AS `id`, l1.`seq`
FROM `_product_category_seed_l1` l1
JOIN `product_category` pc
  ON pc.`name` = l1.`level1`
  AND COALESCE(pc.`parent_id`, 0) = 0
  AND COALESCE(pc.`deleted`, 0) = 0
  AND (pc.`tenant_id` <=> @product_category_seed_tenant_id)
